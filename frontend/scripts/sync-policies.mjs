import fs from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const frontend = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
for (const [route, title, component] of [
  ['privacy', 'Privacy policy', 'Privacy'],
  ['data-deletion', 'Data deletion instructions', 'Deletion'],
]) {
  const source = await fs.readFile(resolve(frontend, '..', route + '.html'), 'utf8');
  const article = source.match(/<article\b[^>]*>[\s\S]*?<\/article>/)?.[0];
  if (!article || /<script\b|\bon\w+\s*=|[{}]/i.test(article)) {
    throw new Error('Expected a static, script-free policy article in ' + route + '.html');
  }
  const jsx = article
    .replace(/\bclass=/g, 'className=')
    .replace(/href="(privacy|data-deletion)\.html"/g, 'href="/$1"')
    .replace(/>\s*</g, '>\n    <');
  const output = `/* oxlint-disable nextjs/no-html-link-for-pages */\n// Static export: use browser navigation for policy cross-links.\n// Generated by scripts/sync-policies.mjs from the root ${route}.html.\n// Keep policy copy in the root document, then run npm run sync:policies.\nimport type { Metadata } from 'next';\nexport const metadata: Metadata = { title: '${title}', alternates: { canonical: '/${route}' } };\nexport default function ${component}() {\n  return ${jsx};\n}\n`;
  const target = resolve(frontend, 'app', route, 'page.tsx');
  if (check) {
    const current = (await fs.readFile(target, 'utf8')).replace(/\r\n/g, '\n');
    if (current !== output) throw new Error(route + ' is out of sync. Run npm run sync:policies.');
  } else {
    await fs.writeFile(target, output);
  }
  console.log((check ? 'Verified ' : 'Updated ') + route + ' from the published policy source.');
}
